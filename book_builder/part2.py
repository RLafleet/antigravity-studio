    add_bullet(doc, "Бинарная или градиентная маска: 0.0 для диэлектриков (кожа гоблина, кости, резина), 1.0 для чистых проводников (стальные латы, золотые кольца, лезвие топора).", "Metallic: ")
    add_bullet(doc, "Определяет микрорельеф поверхности (размер микрофасеток): 0.0 — абсолютно полированное зеркало (четкий блик), 1.0 — матовая шероховатая поверхность (полное рассеяние блика).", "Roughness: ")
    add_bullet(doc, "Цвет и интенсивность самосвечения участков тела (лавовые трещины, светящиеся глаза, токсичные наросты). Не зависит от внешних источников света сцены.", "Emissive: ")
