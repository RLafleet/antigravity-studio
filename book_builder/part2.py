    add_bullet(doc, "Концентрические круговые петли, повторяющие круговую мышцу рта (Orbicularis Oris) и круговую мышцу глаза (Orbicularis Oculi). Необходимы для лицевого скиннинга и морф-таргетов.", "Лицо и челюсть: ")

