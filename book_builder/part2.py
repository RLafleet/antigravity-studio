    add_bullet(doc, "Типизированный итератор (Accessor). Накладывает строгий тип данных на срез BufferView: тип компонентов (5126 = FLOAT, 5123 = UNSIGNED_SHORT, 5121 = UNSIGNED_BYTE), топологию вектора (SCALAR, VEC2, VEC3, VEC4, MAT4), а также хранит предварительно вычисленные Bounding Box (минимальные и максимальные значения координат min[3] и max[3]).", "3. Accessor: ")

