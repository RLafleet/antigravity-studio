    add_bullet(doc, "Аксессор типа VEC4 (FLOAT или нормализованный UNSIGNED_SHORT), содержащий веса влияния соответствующих 4 костей. Сумма значений в векторе строго равна 1.0.", "WEIGHTS_0: ")

